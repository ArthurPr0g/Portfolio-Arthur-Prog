/** Recebe o conteúdo em português e devolve o mesmo conteúdo com os textos em inglês. */
export function traduzir(PT) {
  const PROJECTS = PT.PROJECTS.map((p) => {
    const en = PROJETOS[p.slug] || {};
    return {
      ...p,
      ...en,
      title: en.title || p.title,
      linkLabel: en.linkLabel || p.linkLabel,
      beforeAfter: p.beforeAfter?.map((b, i) => ({ ...b, label: en.beforeAfter?.[i] || b.label })),
      gallery: p.gallery.map((g, i) => ({ ...g, caption: en.captions?.[i] || g.caption })),
    };
  });

  return {
    ...PT,
    PROJECTS,
    TICKER: TEXTOS.TICKER,
    PIPELINE: PT.PIPELINE.map((p, i) => ({ ...p, label: TEXTOS.PIPELINE[i] })),
    PILARES: TEXTOS.PILARES,
    ETAPAS: PT.ETAPAS.map((e, i) => ({ ...e, title: TEXTOS.ETAPAS[i][0], desc: TEXTOS.ETAPAS[i][1] })),
    FERRAMENTAS: PT.FERRAMENTAS.map((f, i) => ({ ...f, desc: TEXTOS.FERRAMENTAS[i] })),
    COMPETENCIAS: TEXTOS.COMPETENCIAS,
    CARREIRA: PT.CARREIRA.map((c, i) => ({ ...c, role: TEXTOS.CARREIRA[i][0], desc: TEXTOS.CARREIRA[i][1] })),
    STATS: PT.STATS.map((s, i) => ({ ...s, label: TEXTOS.STATS[i] })),
    DEPOIMENTOS: PT.DEPOIMENTOS.map((d, i) => ({ ...d, ...TEXTOS.DEPOIMENTOS[i] })),
  };
}
